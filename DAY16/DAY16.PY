# COMPLETE SALES DATA EDA PROJECT
import pandas as pd
import numpy as np
import matplotlib.pyplot as plt

# STEP 1: CREATE SAMPLE DATASET
data = {
    'Date': [
        '2024-01-05', '2024-01-12', '2024-02-10',
        '2024-02-18', '2024-03-05', '2024-03-20',
        '2024-04-08', '2024-04-15', '2024-05-10',
        '2024-05-25'
    ],
    
    'Product': [
        'Laptop', 'Phone', 'Tablet',
        'Laptop', 'Phone', 'Tablet',
        'Laptop', 'Phone', 'Tablet',
        np.nan
    ],
    
    'Region': [
        'North', 'South', 'East',
        'West', 'North', 'South',
        'East', 'West', np.nan,
        'North'
    ],
    
    'Sales': [
        50000, 30000, 20000,
        np.nan, 45000, 25000,
        60000, 35000, 22000,
        40000
    ]
}

df = pd.DataFrame(data)

print("Original Dataset:\n")
print(df)

# STEP 2: DATA CLEANING
print("\nMissing Values Before Cleaning:\n")
print(df.isnull().sum())

# Fill missing Product & Region
df['Product'].fillna('Unknown', inplace=True)
df['Region'].fillna('Unknown', inplace=True)

# Fill missing Sales with mean
df['Sales'].fillna(df['Sales'].mean(), inplace=True)

# Convert Date column to datetime
df['Date'] = pd.to_datetime(df['Date'])

print("\nDataset After Cleaning:\n")
print(df)

# STEP 3: TOTAL SALES PER PRODUCT
product_sales = df.groupby('Product')['Sales'].sum().sort_values(ascending=False)

print("\nTotal Sales Per Product:\n")
print(product_sales)

# STEP 4: REGION-WISE PERFORMANCE
region_sales = df.groupby('Region')['Sales'].sum().sort_values(ascending=False)

print("\nRegion-wise Sales:\n")
print(region_sales)

# STEP 5: MONTHLY GROWTH ANALYSIS
df['Month'] = df['Date'].dt.strftime('%B')

monthly_sales = df.groupby('Month')['Sales'].sum()

print("\nMonthly Sales:\n")
print(monthly_sales)

# STEP 6: BEST PERFORMING REGION
best_region = region_sales.idxmax()

print(f"\nBest Performing Region: {best_region}")

# STEP 7: SALES TREND LINE CHART
daily_sales = df.groupby('Date')['Sales'].sum()

plt.figure(figsize=(10,5))
plt.plot(daily_sales.index, daily_sales.values, marker='o')
plt.title("Sales Trend Over Time")
plt.xlabel("Date")
plt.ylabel("Sales")
plt.grid(True)
plt.show()

# STEP 8: TOP PRODUCTS BAR CHART
plt.figure(figsize=(8,5))
plt.bar(product_sales.index, product_sales.values)
plt.title("Top Products by Sales")
plt.xlabel("Product")
plt.ylabel("Total Sales")
plt.show()

# STEP 9: KEY INSIGHTS
print("\nKEY INSIGHTS")
print("-------------")

print(f"1. Highest sales generated by: {product_sales.idxmax()}")

print(f"2. Best performing region: {best_region}")

print(f"3. Total sales across all products: {df['Sales'].sum():,.2f}")

print(f"4. Number of missing values handled successfully.")

print(f"5. Monthly sales analysis completed successfully.")